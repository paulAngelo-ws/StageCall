-- Durable organization activity and per-user read state.
begin;
create table if not exists public.organization_notifications (
    id integer generated by default as identity primary key,
    organization_id text not null references public.organizations(id) on delete cascade,
    post_id integer references public.campus_posts(id) on delete cascade,
    kind text not null check (kind in ('post', 'recruitment', 'organization')),
    title text not null,
    message text not null,
    created_at timestamptz not null default now()
);
create index if not exists organization_notifications_created_idx on public.organization_notifications (created_at desc, id desc);
alter table public.organization_notifications enable row level security;
revoke all on public.organization_notifications from public, anon, authenticated;
grant select on public.organization_notifications to authenticated;
drop policy if exists "Read visible organization notifications" on public.organization_notifications;
create policy "Read visible organization notifications" on public.organization_notifications for select to authenticated using (
    post_id is null or exists (select 1 from public.campus_posts p where p.id = post_id)
);

create table if not exists public.organization_notification_reads (
    user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    notification_id integer not null references public.organization_notifications(id) on delete cascade,
    primary key (user_id, notification_id)
);
alter table public.organization_notification_reads enable row level security;
revoke all on public.organization_notification_reads from public, anon, authenticated;
grant select, insert on public.organization_notification_reads to authenticated;
drop policy if exists "Read own notification receipts" on public.organization_notification_reads;
create policy "Read own notification receipts" on public.organization_notification_reads for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists "Create own visible notification receipts" on public.organization_notification_reads;
create policy "Create own visible notification receipts" on public.organization_notification_reads for insert to authenticated with check (
    user_id = (select auth.uid()) and exists (select 1 from public.organization_notifications n where n.id = notification_id)
);

-- A new campus post inserts a notification here. NotificationStore.kt later reads it for NotificationsScreen.kt.
create or replace function public.stagecall_notify_post() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
    insert into public.organization_notifications (organization_id, post_id, kind, title, message, created_at)
    values (new.organization_id, new.id, 'post',
        case new.category when 'Events' then 'New activity: ' when 'Announcements' then 'New announcement: ' else 'New post: ' end || new.title,
        new.message, new.created_at);
    return new;
end;
$$;
drop trigger if exists stagecall_post_notification on public.campus_posts;
create trigger stagecall_post_notification after insert on public.campus_posts for each row execute function public.stagecall_notify_post();

-- Existing posts also appear in the activity feed when this migration is applied.
insert into public.organization_notifications (organization_id, post_id, kind, title, message, created_at)
select p.organization_id, p.id, 'post',
    case p.category when 'Events' then 'New activity: ' when 'Announcements' then 'New announcement: ' else 'New post: ' end || p.title,
    p.message, p.created_at
from public.campus_posts p where not exists (select 1 from public.organization_notifications n where n.post_id = p.id);

create or replace function public.stagecall_notify_organization_update() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
    if old.is_recruiting is distinct from new.is_recruiting then
        insert into public.organization_notifications (organization_id, kind, title, message)
        values (new.id, 'recruitment', case when new.is_recruiting then 'Applications are open' else 'Applications are closed' end,
            case when new.is_recruiting then 'This organization is accepting applications.' else 'This organization is no longer accepting applications.' end);
    end if;
    if old.about_headline is distinct from new.about_headline or old.full_description is distinct from new.full_description
       or old.banner_color is distinct from new.banner_color then
        insert into public.organization_notifications (organization_id, kind, title, message)
        values (new.id, 'organization', 'Organization details updated', 'The organization updated its profile.');
    end if;
    return new;
end;
$$;
drop trigger if exists stagecall_organization_notification on public.organizations;
create trigger stagecall_organization_notification after update on public.organizations for each row execute function public.stagecall_notify_organization_update();

-- Runs with the caller's privileges and RLS, including for bulk marking.
-- NotificationStore.kt sends a notification ID or a bulk request. The read receipt is included in the next sync from 202611180017_incremental_sync.sql.
create or replace function public.mark_organization_notifications_read(p_notification_id integer default null)
returns void language sql security invoker set search_path = '' as $$
    insert into public.organization_notification_reads (user_id, notification_id)
    select auth.uid(), n.id from public.organization_notifications n
    where p_notification_id is null or n.id = p_notification_id
    on conflict (user_id, notification_id) do nothing;
$$;
revoke all on function public.mark_organization_notifications_read(integer) from public, anon, authenticated;
grant execute on function public.mark_organization_notifications_read(integer) to authenticated;
commit;
