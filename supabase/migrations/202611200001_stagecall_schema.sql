-- StageCall schema for a new Supabase project.
-- Supabase supplies the auth and storage schemas. Configure the Auth hooks after install.
begin;

-- Catalog and posts
create table public.organizations (
    id text primary key,
    name text not null,
    category text not null,
    description text not null,
    short_tagline text not null,
    about_headline text not null,
    full_description text not null,
    member_count integer not null default 0 check (member_count >= 0),
    is_recruiting boolean not null default false,
    requirements jsonb not null default '[]'::jsonb check (jsonb_typeof(requirements) = 'array'),
    photo_path text,
    next_activity_title text not null default '',
    next_activity_schedule text not null default '',
    banner_color text not null default 'blue'
        check (banner_color in ('blue', 'green', 'purple', 'orange', 'indigo', 'gold'))
);

create table public.campus_posts (
    id integer generated by default as identity primary key,
    organization_id text not null references public.organizations(id) on delete cascade,
    title text not null,
    message text not null,
    category text not null,
    members_only boolean not null default false,
    schedule text not null default '',
    created_at timestamptz not null default now(),
    image_path text
);

create index campus_posts_organization_id_idx on public.campus_posts(organization_id);

create index campus_posts_image_path_idx on public.campus_posts (image_path) where image_path is not null;

-- Accounts, memberships, and applications
create table public.user_profiles (
    user_id uuid primary key references auth.users(id) on delete cascade,
    bio text not null default '' check (char_length(bio) <= 500),
    dark_theme boolean not null default false,
    bookmarks text[] not null default '{}'
);

create table public.organization_memberships (
    organization_id text not null references public.organizations(id) on delete cascade,
    user_id uuid not null references auth.users(id) on delete cascade,
    role text not null default 'Member' check (role in ('Member', 'President')),
    created_at timestamptz not null default now(),
    primary key (organization_id, user_id)
);

create index organization_memberships_user_id_idx on public.organization_memberships(user_id);

create table public.membership_applications (
    id integer generated always as identity primary key,
    user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    organization_id text not null references public.organizations(id),
    applicant_name text not null check (length(trim(applicant_name)) between 1 and 200),
    applicant_email text not null check (length(trim(applicant_email)) between 3 and 320),
    student_number text not null check (length(trim(student_number)) > 0 and char_length(student_number) <= 50),
    year_level text not null check (year_level in ('1st Year', '2nd Year', '3rd Year', '4th Year')),
    reason text not null check (length(trim(reason)) > 0 and char_length(reason) <= 1000),
    status text not null default 'Pending' check (status in ('Pending', 'Accepted', 'Rejected')),
    decision text not null default '',
    submitted_at timestamptz not null default now(),
    updated_at timestamptz,
    unique (user_id, organization_id)
);

create index membership_applications_review_idx on public.membership_applications (organization_id, submitted_at desc);

-- Organization registrations
create table public.stagecall_admins (
    user_id uuid primary key references auth.users(id) on delete cascade
);

create table public.organization_registrations (
    id integer generated always as identity primary key,
    applicant_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    applicant_email text not null default coalesce(auth.jwt()->>'email', ''),
    name text not null check (char_length(btrim(name)) between 1 and 100),
    category text not null check (char_length(btrim(category)) between 1 and 60),
    tagline text not null check (char_length(btrim(tagline)) between 1 and 200),
    description text not null check (char_length(btrim(description)) between 1 and 2000),
    status text not null default 'Pending' check (status in ('Pending', 'Accepted', 'Rejected')),
    decision text not null default '',
    organization_id text references public.organizations(id) on delete set null,
    submitted_at timestamptz not null default now(),
    reviewed_at timestamptz,
    reviewed_by uuid references auth.users(id) on delete set null
);

create unique index organization_registrations_pending_name_idx
    on public.organization_registrations (applicant_id, lower(btrim(name))) where status = 'Pending';

-- Notifications and read receipts
create table public.organization_notifications (
    id integer generated by default as identity primary key,
    organization_id text references public.organizations(id) on delete cascade,
    post_id integer references public.campus_posts(id) on delete cascade,
    application_id integer references public.membership_applications(id) on delete cascade,
    registration_id integer references public.organization_registrations(id) on delete cascade,
    kind text not null check (kind in ('post', 'recruitment', 'organization', 'application_review',
        'registration_review', 'registration_decision')),
    title text not null,
    message text not null,
    created_at timestamptz not null default now(),
    constraint organization_notifications_registration_scope_check check (
        case when kind in ('registration_review', 'registration_decision') then
            registration_id is not null and organization_id is null and post_id is null and application_id is null
        else registration_id is null and organization_id is not null end
    )
);

create table public.organization_notification_reads (
    user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    notification_id integer not null references public.organization_notifications(id) on delete cascade,
    primary key (user_id, notification_id)
);

create index organization_notifications_created_idx on public.organization_notifications (created_at desc, id desc);

create unique index organization_notifications_application_idx
    on public.organization_notifications (application_id) where application_id is not null;

create unique index organization_notifications_registration_idx
    on public.organization_notifications (registration_id, kind) where registration_id is not null;

create index organization_notifications_post_idx on public.organization_notifications (post_id) where post_id is not null;
create index organization_notification_reads_notification_idx on public.organization_notification_reads (notification_id);

-- Row-level access
create policy "Read public organizations" on public.organizations
    for select to anon, authenticated using (true);

create policy "Read public posts" on public.campus_posts
    for select to anon, authenticated using (not members_only);

create policy "Members read organization posts" on public.campus_posts
    for select to authenticated using (
        members_only and exists (
            select 1 from public.organization_memberships m
            where m.organization_id = campus_posts.organization_id and m.user_id = (select auth.uid())
        )
    );

create policy "Users read own profile" on public.user_profiles for select to authenticated
    using (user_id = (select auth.uid()));

create policy "Users insert own profile" on public.user_profiles for insert to authenticated
    with check (user_id = (select auth.uid()));

create policy "Users update own profile" on public.user_profiles for update to authenticated
    using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

create policy "Applicants read own applications" on public.membership_applications
    for select to authenticated using (user_id = (select auth.uid()));

create policy "Users read own memberships" on public.organization_memberships
    for select to authenticated using (user_id = (select auth.uid()));

create policy "Applicants submit own applications" on public.membership_applications
    for insert to authenticated with check (
        user_id = (select auth.uid()) and exists (
            select 1 from public.organizations o where o.id = organization_id and o.is_recruiting
        ) and not exists (
            select 1 from public.organization_memberships m
            where m.organization_id = membership_applications.organization_id and m.user_id = (select auth.uid())
        )
    );

create policy "Admins read own role" on public.stagecall_admins
    for select to authenticated using (user_id = (select auth.uid()));

create policy "Applicants and admins read registrations" on public.organization_registrations
    for select to authenticated using (
        applicant_id = (select auth.uid()) or exists (
            select 1 from public.stagecall_admins where user_id = (select auth.uid())
        )
    );

create policy "Applicants submit their own registrations" on public.organization_registrations
    for insert to authenticated with check (
        applicant_id = (select auth.uid()) and status = 'Pending'
    );

create policy "Read visible organization notifications" on public.organization_notifications
    for select to authenticated using (
        case when kind = 'application_review' then exists (
            select 1 from public.organization_memberships m
            where m.organization_id = organization_notifications.organization_id
                and m.user_id = (select auth.uid()) and m.role = 'President'
        ) when kind = 'registration_review' then exists (
            select 1 from public.stagecall_admins a where a.user_id = (select auth.uid())
        ) when kind = 'registration_decision' then exists (
            select 1 from public.organization_registrations r
            where r.id = organization_notifications.registration_id and r.applicant_id = (select auth.uid())
        ) else (
            post_id is null or exists (select 1 from public.campus_posts p where p.id = post_id)
        ) end
    );

create policy "Read own notification receipts" on public.organization_notification_reads for select to authenticated using (user_id = (select auth.uid()));

create policy "Create own visible notification receipts" on public.organization_notification_reads for insert to authenticated with check (
    user_id = (select auth.uid()) and exists (select 1 from public.organization_notifications n where n.id = notification_id)
);

-- University account hooks and profile updates
create function public.stagecall_before_user_created(event jsonb)
returns jsonb language plpgsql stable set search_path = '' as $$
begin
    if coalesce(event->'user'->>'email', '') !~* '^[^@[:space:]]+@([a-z0-9-]+\.)*ubaguio\.edu$' then
        return jsonb_build_object('error', jsonb_build_object(
            'http_code', 403, 'message', 'Please sign in with your University of Baguio Google account.'
        ));
    end if;
    return '{}'::jsonb;
end;
$$;

create function public.stagecall_restrict_access_token(event jsonb)
returns jsonb language plpgsql stable set search_path = '' as $$
begin
    if coalesce(event->'claims'->>'email', '') !~* '^[^@[:space:]]+@([a-z0-9-]+\.)*ubaguio\.edu$' then
        return jsonb_build_object('error', jsonb_build_object(
            'http_code', 403, 'message', 'Please sign in with your University of Baguio Google account.'
        ));
    end if;
    return jsonb_build_object('claims', event->'claims');
end;
$$;

create function public.update_own_profile(
    p_user_id uuid, p_bio text default null, p_dark_theme boolean default null, p_bookmarks text[] default null
) returns void language plpgsql security invoker set search_path = '' as $$
begin
    if auth.uid() is null or auth.uid() <> p_user_id then
        raise exception 'Account has changed' using errcode = '42501';
    end if;
    if p_bio is not null and char_length(p_bio) > 500 then raise exception 'Bio too long'; end if;
    insert into public.user_profiles (user_id, bio, dark_theme, bookmarks)
    values (auth.uid(), coalesce(p_bio, ''), coalesce(p_dark_theme, false), coalesce(p_bookmarks, '{}'::text[]))
    on conflict (user_id) do update set
        bio = coalesce(p_bio, public.user_profiles.bio),
        dark_theme = coalesce(p_dark_theme, public.user_profiles.dark_theme),
        bookmarks = coalesce(p_bookmarks, public.user_profiles.bookmarks);
end;
$$;

-- Membership counts, roster, and application review
create function public.stagecall_update_member_count()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
    if tg_op = 'TRUNCATE' then
        update public.organizations set member_count = 0 where member_count <> 0;
        return null;
    end if;
    if tg_op = 'UPDATE' and old.organization_id = new.organization_id then
        return null;
    end if;
    if tg_op in ('DELETE', 'UPDATE') then
        update public.organizations set member_count = member_count - 1 where id = old.organization_id;
    end if;
    if tg_op in ('INSERT', 'UPDATE') then
        update public.organizations set member_count = member_count + 1 where id = new.organization_id;
    end if;
    return null;
end;
$$;

create trigger stagecall_membership_count
    after insert or delete or update of organization_id on public.organization_memberships
    for each row execute function public.stagecall_update_member_count();

create trigger stagecall_membership_count_reset
    after truncate on public.organization_memberships
    for each statement execute function public.stagecall_update_member_count();

create function public.list_organization_members(p_organization_id text)
returns table (user_id uuid, name text, picture text, bio text, role text, joined_at timestamptz)
language sql stable security definer set search_path = '' as $$
    select m.user_id,
        coalesce(nullif(btrim(u.raw_user_meta_data ->> 'full_name'), ''), 'Campus member'),
        coalesce(nullif(u.raw_user_meta_data ->> 'avatar_url', ''), u.raw_user_meta_data ->> 'picture', ''),
        coalesce(p.bio, ''),
        m.role,
        m.created_at
    from public.organization_memberships m
    join auth.users u on u.id = m.user_id
    left join public.user_profiles p on p.user_id = m.user_id
    where auth.uid() is not null and m.organization_id = p_organization_id
    order by (m.role = 'President') desc, lower(coalesce(u.raw_user_meta_data ->> 'full_name', '')), m.user_id;
$$;

create function public.get_organization_member_details(p_organization_id text, p_user_id uuid)
returns table (email text, shared_organizations text[])
language sql stable security definer set search_path = '' as $$
    select u.email::text, array(
        select o.name
        from public.organization_memberships target
        join public.organization_memberships viewer
            on viewer.organization_id = target.organization_id and viewer.user_id = (select auth.uid())
        join public.organizations o on o.id = target.organization_id
        where target.user_id = m.user_id and viewer.user_id <> m.user_id
        order by lower(o.name), o.id
    )
    from public.organization_memberships m
    join auth.users u on u.id = m.user_id
    where (select auth.uid()) is not null
        and m.organization_id = p_organization_id and m.user_id = p_user_id;
$$;

create function public.leave_organization(p_organization_id text)
returns void language plpgsql security definer set search_path = '' as $$
declare
    v_user_id uuid := auth.uid();
begin
    if v_user_id is null then
        raise exception 'Sign in to leave an organization' using errcode = '42501';
    end if;

    delete from public.organization_memberships m
    where m.organization_id = p_organization_id and m.user_id = v_user_id;
end;
$$;

create function public.remove_organization_member(p_organization_id text, p_user_id uuid)
returns void language plpgsql security definer set search_path = '' as $$
begin
    perform 1 from public.organization_memberships m
        where m.organization_id = p_organization_id and m.user_id = auth.uid() and m.role = 'President'
        for share;
    if not found then
        raise exception 'President access is required' using errcode = '42501';
    end if;

    -- Restrict removal to ordinary members and allow retries after a successful delete.
    delete from public.organization_memberships m
        where m.organization_id = p_organization_id and m.user_id = p_user_id and m.role = 'Member';
end;
$$;

create function public.review_organization_applications(p_organization_id text)
returns setof public.membership_applications
language plpgsql security definer set search_path = '' as $$
begin
    if auth.uid() is null or not exists (
        select 1 from public.organization_memberships m
        where m.organization_id = p_organization_id and m.user_id = auth.uid() and m.role = 'President'
    ) then
        raise exception 'Not authorized to review applications' using errcode = '42501';
    end if;
    return query select a.* from public.membership_applications a
        where a.organization_id = p_organization_id and a.user_id <> auth.uid()
        order by a.submitted_at desc;
end;
$$;

create function public.decide_organization_application(
    p_organization_id text, p_application_id integer, p_status text, p_decision text default ''
) returns void language plpgsql security definer set search_path = '' as $$
declare v_user_id uuid;
begin
    if auth.uid() is null then
        raise exception 'Not authorized' using errcode = '42501';
    end if;
    -- Hold the role row until commit, so revocation and a decision cannot race.
    perform 1 from public.organization_memberships m
        where m.organization_id = p_organization_id and m.user_id = auth.uid() and m.role = 'President'
        for share;
    if not found then
        raise exception 'Not authorized to review applications' using errcode = '42501';
    end if;
    if p_status is null or p_status not in ('Accepted', 'Rejected') or p_decision is null or length(p_decision) > 2000 then
        raise exception 'Invalid decision';
    end if;
    update public.membership_applications a
        set status = p_status, decision = trim(p_decision), updated_at = now()
        where a.id = p_application_id and a.organization_id = p_organization_id
          and a.status = 'Pending' and a.user_id <> auth.uid()
        returning a.user_id into v_user_id;
    if not found then
        raise exception 'Application unavailable or already reviewed';
    end if;
    if p_status = 'Accepted' then
        insert into public.organization_memberships (organization_id, user_id, role)
            values (p_organization_id, v_user_id, 'Member')
            on conflict (organization_id, user_id) do nothing;
    end if;
end;
$$;

-- Organization settings and registration review
create function public.update_organization_settings(
    p_organization_id text, p_about_headline text, p_full_description text,
    p_is_recruiting boolean, p_banner_color text,
    p_requirements text[] default null, p_photo_path text default null, p_remove_photo boolean default false
) returns void language plpgsql security definer set search_path = '' as $$
begin
    perform 1 from public.organization_memberships m
        where m.organization_id = p_organization_id and m.user_id = auth.uid() and m.role = 'President'
        for share;
    if not found then
        raise exception 'Not authorized to edit organization' using errcode = '42501';
    end if;
    if p_about_headline is null or length(trim(p_about_headline)) not between 1 and 120
       or p_full_description is null or length(trim(p_full_description)) not between 1 and 5000
       or p_is_recruiting is null or p_banner_color is null
       or p_banner_color not in ('blue', 'green', 'purple', 'orange', 'indigo', 'gold') then
        raise exception 'Invalid organization settings';
    end if;
    if p_photo_path is not null and not exists (
        select 1 from storage.objects o
        where o.bucket_id = 'organization-photos' and o.name = p_photo_path
            and (storage.foldername(o.name))[1] = p_organization_id
            and (storage.foldername(o.name))[2] = auth.uid()::text
    ) then raise exception 'Invalid organization photo'; end if;

    update public.organizations set about_headline = trim(p_about_headline),
        full_description = trim(p_full_description), is_recruiting = p_is_recruiting,
        banner_color = p_banner_color,
        requirements = coalesce((
            select jsonb_agg(btrim(entry) order by position)
            from unnest(p_requirements) with ordinality as submitted(entry, position)
            where btrim(entry) <> ''
        ), case when p_requirements is not null then '[]'::jsonb else requirements end),
        photo_path = case when p_remove_photo then null else coalesce(p_photo_path, photo_path) end
    where id = p_organization_id;
    if not found then raise exception 'Organization not found'; end if;
end;
$$;

create function public.decide_organization_registration(p_id integer, p_approve boolean, p_decision text)
returns void language plpgsql security definer set search_path = '' as $$
declare
    v_registration public.organization_registrations%rowtype;
    v_organization_id text;
begin
    perform 1 from public.stagecall_admins where user_id = auth.uid() for share;
    if not found then
        raise exception 'Administrator access required' using errcode = '42501';
    end if;
    if p_approve is null or p_decision is null or char_length(btrim(p_decision)) > 1000 then
        raise exception 'Invalid decision';
    end if;

    select * into v_registration from public.organization_registrations
    where id = p_id and status = 'Pending'
    for update;
    if not found then
        raise exception 'Registration unavailable or already reviewed';
    end if;

    if p_approve then
        -- Serialize approvals of the same normalized name.
        perform pg_catalog.pg_advisory_xact_lock(912515, pg_catalog.hashtext(lower(btrim(v_registration.name))));
        if exists (
            select 1 from public.organizations where lower(btrim(name)) = lower(btrim(v_registration.name))
        ) then
            raise exception 'An organization with this name already exists' using errcode = '23505';
        end if;
        v_organization_id := 'registration-' || v_registration.id;
        insert into public.organizations (id, name, category, description, short_tagline, about_headline, full_description)
        values (v_organization_id, btrim(v_registration.name), btrim(v_registration.category),
                btrim(v_registration.tagline), btrim(v_registration.tagline), 'About us', btrim(v_registration.description));
        insert into public.organization_memberships (organization_id, user_id, role)
        values (v_organization_id, v_registration.applicant_id, 'President');
    end if;

    update public.organization_registrations
    set status = case when p_approve then 'Accepted' else 'Rejected' end,
        decision = btrim(p_decision), organization_id = v_organization_id,
        reviewed_by = auth.uid(), reviewed_at = now()
    where id = p_id;
end;
$$;

