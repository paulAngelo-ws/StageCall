create function public.create_organization_post(
    p_organization_id text, p_title text, p_message text, p_category text,
    p_schedule text, p_members_only boolean, p_image_path text
) returns setof public.campus_posts
language plpgsql security definer set search_path = '' as $$
begin
    perform 1 from public.organization_memberships m where m.organization_id = p_organization_id
        and m.user_id = auth.uid() and m.role = 'President' for share;
    if not found then raise exception 'Not authorized to post for this organization' using errcode = '42501'; end if;
    if p_title is null or length(trim(p_title)) not between 1 and 120
       or p_message is null or length(trim(p_message)) not between 1 and 5000
       or p_category is null or p_category not in ('Recruitment', 'Events', 'Announcements')
       or p_schedule is null or length(trim(p_schedule)) > 200 or p_members_only is null then
        raise exception 'Invalid post';
    end if;
    if p_image_path is not null and not exists (
        select 1 from storage.objects o where o.bucket_id = 'post-images' and o.name = p_image_path
          and (storage.foldername(o.name))[1] = p_organization_id
          and (storage.foldername(o.name))[2] = auth.uid()::text
    ) then raise exception 'Invalid post image'; end if;
    return query insert into public.campus_posts (organization_id, title, message, category, schedule, members_only, image_path)
        values (p_organization_id, trim(p_title), trim(p_message), p_category, trim(p_schedule), p_members_only, p_image_path)
        returning *;
end;
$$;

create function public.update_organization_post(
    p_organization_id text, p_title text, p_message text, p_category text,
    p_schedule text, p_members_only boolean, p_image_path text,
    p_post_id integer, p_remove_image boolean
) returns setof public.campus_posts
language plpgsql security definer set search_path = '' as $$
declare
    v_post public.campus_posts%rowtype;
begin
    perform 1 from public.organization_memberships m where m.organization_id = p_organization_id
        and m.user_id = auth.uid() and m.role = 'President' for share;
    if not found then raise exception 'Not authorized to edit posts for this organization' using errcode = '42501'; end if;
    if p_title is null or length(trim(p_title)) not between 1 and 120
       or p_message is null or length(trim(p_message)) not between 1 and 5000
       or p_category is null or p_category not in ('Recruitment', 'Events', 'Announcements')
       or p_schedule is null or length(trim(p_schedule)) > 200 or p_members_only is null then
        raise exception 'Invalid post';
    end if;
    if p_image_path is not null and not exists (
        select 1 from storage.objects o where o.bucket_id = 'post-images' and o.name = p_image_path
          and (storage.foldername(o.name))[1] = p_organization_id
          and (storage.foldername(o.name))[2] = auth.uid()::text
    ) then raise exception 'Invalid post image'; end if;
    update public.campus_posts p
    set title = trim(p_title), message = trim(p_message), category = p_category,
        schedule = trim(p_schedule), members_only = p_members_only,
        image_path = case when p_remove_image then null else coalesce(p_image_path, p.image_path) end
    where p.id = p_post_id and p.organization_id = p_organization_id
    returning p.* into v_post;
    if not found then raise exception 'Post unavailable for this organization'; end if;

    update public.organization_notifications n
    set title = case v_post.category when 'Events' then 'New activity: '
        when 'Announcements' then 'New announcement: ' else 'New post: ' end || v_post.title,
        message = v_post.message
    where n.post_id = v_post.id and n.kind = 'post';

    return next v_post;
end;
$$;

-- Notification delivery and read state
create function public.stagecall_notify_post() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
    insert into public.organization_notifications (organization_id, post_id, kind, title, message, created_at)
    values (new.organization_id, new.id, 'post',
        case new.category when 'Events' then 'New activity: ' when 'Announcements' then 'New announcement: ' else 'New post: ' end || new.title,
        new.message, new.created_at);
    return new;
end;
$$;

create function public.stagecall_notify_organization_update() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
    if old.is_recruiting is distinct from new.is_recruiting then
        insert into public.organization_notifications (organization_id, kind, title, message)
        values (new.id, 'recruitment', case when new.is_recruiting then 'Applications are open' else 'Applications are closed' end,
            case when new.is_recruiting then 'This organization is accepting applications.' else 'This organization is no longer accepting applications.' end);
    end if;
    if old.about_headline is distinct from new.about_headline or old.full_description is distinct from new.full_description
       or old.banner_color is distinct from new.banner_color then
        insert into public.organization_notifications (organization_id, kind, title, message)
        values (new.id, 'organization', 'Organization details updated', 'The organization updated its profile.');
    end if;
    return new;
end;
$$;

create function public.mark_organization_notifications_read(p_notification_id integer default null)
returns void language sql security invoker set search_path = '' as $$
    insert into public.organization_notification_reads (user_id, notification_id)
    select auth.uid(), n.id from public.organization_notifications n
    where p_notification_id is null or n.id = p_notification_id
    on conflict (user_id, notification_id) do nothing;
$$;

